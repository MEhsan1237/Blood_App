import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import '../../services/auth_service.dart';
import '../../services/notification_service.dart';
import '../../utils/constants.dart';
import '../../models/blood_request_model.dart';

class CreateRequestSheet extends StatefulWidget {
  const CreateRequestSheet({super.key});

  @override
  State<CreateRequestSheet> createState() => _CreateRequestSheetState();
}

class _CreateRequestSheetState extends State<CreateRequestSheet> {
  final _formKey = GlobalKey<FormState>();
  
  // Form fields
  String _selectedBloodGroup = 'O+';
  final _cityController = TextEditingController();
  final _hospitalController = TextEditingController();
  final _unitsController = TextEditingController(text: '1');
  final _descriptionController = TextEditingController();
  String _selectedUrgency = 'Medium';
  bool _isLoading = false;

  final List<String> _bloodGroups = ['A+', 'A-', 'B+', 'B-', 'O+', 'O-', 'AB+', 'AB-'];
  final List<String> _urgencies = ['Low', 'Medium', 'High'];

  /// Saves the blood request to Firestore
  Future<void> _submitRequest() async {
    if (!_formKey.currentState!.validate()) return;

    setState(() => _isLoading = true);
    
    final authService = Provider.of<AuthService>(context, listen: false);
    final user = await authService.getUserData();

    if (user == null) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Error: User not found')),
        );
      }
      setState(() => _isLoading = false);
      return;
    }

    final newRequest = BloodRequest(
      id: '', // Will be generated by Firestore
      requesterId: user.uid,
      requesterName: user.name,
      bloodGroup: _selectedBloodGroup,
      city: _cityController.text.trim(),
      hospital: _hospitalController.text.trim(),
      units: int.parse(_unitsController.text),
      date: DateTime.now(),
      description: _descriptionController.text.trim(),
      urgency: _selectedUrgency,
    );

    try {
      final docRef = await FirebaseFirestore.instance.collection('requests').add(newRequest.toMap());
      
      // Send notifications to matching donors
      if (mounted) {
        final notificationService = Provider.of<NotificationService>(context, listen: false);
        await notificationService.sendBloodRequestNotification(
          bloodGroup: _selectedBloodGroup,
          city: _cityController.text.trim(),
          requesterName: user.name,
          requesterId: user.uid,
          requestId: docRef.id,
        );
      }

      if (mounted) {
        Navigator.pop(context);
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Request posted successfully!'), backgroundColor: AppColors.success),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Error: ${e.toString()}'), backgroundColor: AppColors.primary),
        );
      }
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    // Making it responsive and adjusting for keyboard
    return Container(
      padding: EdgeInsets.only(
        left: 20,
        right: 20,
        top: 20,
        bottom: MediaQuery.of(context).viewInsets.bottom + 20
      ),
      child: Form(
        key: _formKey,
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const Text(
                'Create Blood Request',
                style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold),
              ),
              const SizedBox(height: 20),
              
              Row(
                children: [
                  Expanded(
                    child: _buildDropdown('Blood Group', _selectedBloodGroup, _bloodGroups, (val) => setState(() => _selectedBloodGroup = val!)),
                  ),
                  const SizedBox(width: 15),
                  Expanded(
                    child: _buildTextField(_unitsController, 'Units Needed', Icons.inventory_2_outlined, keyboardType: TextInputType.number),
                  ),
                ],
              ),
              
              _buildTextField(_cityController, 'City', Icons.location_on_outlined),
              _buildTextField(_hospitalController, 'Hospital Name', Icons.local_hospital_outlined),
              _buildTextField(_descriptionController, 'Description / Reason', Icons.description_outlined),
              
              _buildDropdown('Urgency Level', _selectedUrgency, _urgencies, (val) => setState(() => _selectedUrgency = val!)),
              
              const SizedBox(height: 30),
              
              SizedBox(
                width: double.infinity,
                height: 50,
                child: ElevatedButton(
                  onPressed: _isLoading ? null : _submitRequest,
                  style: ElevatedButton.styleFrom(
                    backgroundColor: AppColors.primary,
                    foregroundColor: Colors.white,
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                    elevation: 0,
                  ),
                  child: _isLoading 
                    ? const CircularProgressIndicator(color: Colors.white) 
                    : const Text('Post Request', style: TextStyle(fontWeight: FontWeight.bold)),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildTextField(TextEditingController controller, String label, IconData icon, {TextInputType keyboardType = TextInputType.text}) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 15),
      child: TextFormField(
        controller: controller,
        keyboardType: keyboardType,
        decoration: InputDecoration(
          labelText: label,
          prefixIcon: Icon(icon, size: 20),
          border: OutlineInputBorder(borderRadius: BorderRadius.circular(12)),
          contentPadding: const EdgeInsets.symmetric(horizontal: 12, vertical: 15),
        ),
        validator: (value) => value == null || value.isEmpty ? 'Required' : null,
      ),
    );
  }

  Widget _buildDropdown(String label, String value, List<String> items, Function(String?) onChanged) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 15),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(label, style: const TextStyle(fontSize: 12, color: Colors.grey)),
          const SizedBox(height: 5),
          DropdownButtonFormField<String>(
            value: value,
            items: items.map((e) => DropdownMenuItem(value: e, child: Text(e))).toList(),
            onChanged: onChanged,
            decoration: InputDecoration(
              contentPadding: const EdgeInsets.symmetric(horizontal: 12),
              border: OutlineInputBorder(borderRadius: BorderRadius.circular(12)),
            ),
          ),
        ],
      ),
    );
  }
}
